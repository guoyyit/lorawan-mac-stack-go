// Package protocol defines the LoRaWAN wire types used by this stack and
// their serialization: Join-Request/Join-Accept (OTAA) and MAC data frames.
package protocol

import (
	"encoding/binary"
	"errors"
	lwcrypto "github.com/guoyyit/lorawan-mac-stack-go/pkg/crypto"
)

var (
	errBadJoinRequest = errors.New("protocol: join request must be 23 bytes")
	errBadJoinAccept  = errors.New("protocol: join accept must be 17 or 33 bytes")
	errShortFrame     = errors.New("protocol: frame shorter than MHDR+MIC")
)

// mhdr builds the MAC header octet for mtype (RFU/version bits stay zero;
// this stack implements LoRaWAN 1.0.x wire compatibility).
func mhdr(t MType) byte { return byte(t) << 5 }

func parseMHDR(b byte) MType { return MType(b >> 5) }

func micOK(got [4]byte, raw []byte) bool {
	if len(raw) < 4 {
		return false
	}
	tail := raw[len(raw)-4:]
	return got[0] == tail[0] && got[1] == tail[1] && got[2] == tail[2] && got[3] == tail[3]
}

// reverseCopy copies src into dst in reverse byte order. Multi-byte
// little-endian-on-the-wire LoRaWAN fields (EUIs) use this.
func reverseCopy(dst []byte, src []byte) {
	for i := range src {
		dst[len(dst)-1-i] = src[i]
	}
}

// EUI64 is an IEEE EUI-64 identifier (JoinEUI / DevEUI).
type EUI64 [8]byte

// DevAddr is a 32-bit device address assigned by the network server.
type DevAddr [4]byte

// DevNonce is the 2-byte join-request nonce generated by the end device.
type DevNonce [2]byte

// AppNonce is the 3-byte join-accept nonce generated by the network server.
type AppNonce [3]byte

// NetID is the 3-byte network identifier.
type NetID [3]byte

// MType identifies the MAC message type (MHDR.MType, LoRaWAN 1.0.x).
type MType uint8

const (
	MTJoinRequest       MType = 0
	MTJoinAccept        MType = 1
	MTUnconfirmedDataUp MType = 2
	MTUnconfirmedDataDN MType = 3
	MTConfirmedDataUp   MType = 4
	MTConfirmedDataDN   MType = 5
)

// FCtrl is the frame control octet.
type FCtrl struct {
	ADR       bool
	ADRACKReq bool
	ACK       bool
	FPending  bool // downlink only (class B bit on uplink, unused here)
	FOptsLen  uint8
}

// JoinRequest is the OTAA Join-Request body.
type JoinRequest struct {
	JoinEUI  EUI64
	DevEUI   EUI64
	DevNonce DevNonce
}

// JoinAccept is the OTAA Join-Accept body.
type JoinAccept struct {
	AppNonce   AppNonce
	NetID      NetID
	DevAddr    DevAddr
	DLSettings byte
	RXDelay    byte
}

// DataFrame is a MAC data frame (FRMPayload held in plaintext form).
type DataFrame struct {
	MType      MType
	DevAddr    DevAddr
	FCtrl      FCtrl
	FCnt       uint16
	FOpts      []MACCommand
	FPort      int // -1 means no FPort/FRMPayload present
	FRMPayload []byte
}

// DecodedFrame is the result of parsing a received data frame.
type DecodedFrame struct {
	DataFrame
	FCnt32   uint32
	MICValid bool
}

// MarshalJoinRequest serializes a Join-Request and appends its MIC.
func MarshalJoinRequest(appKey lwcrypto.AES128Key, req JoinRequest) ([]byte, error) {
	raw := make([]byte, 23)
	raw[0] = mhdr(MTJoinRequest)
	reverseCopy(raw[1:9], req.JoinEUI[:])
	reverseCopy(raw[9:17], req.DevEUI[:])
	copy(raw[17:19], req.DevNonce[:])
	mic := lwcrypto.JoinMessageMIC(appKey, raw[:19])
	copy(raw[19:23], mic[:])
	return raw, nil
}

// ParseJoinRequest parses a Join-Request body (without MIC verification).
func ParseJoinRequest(raw []byte) (*JoinRequest, error) {
	if len(raw) != 23 {
		return nil, errBadJoinRequest
	}
	if parseMHDR(raw[0]) != MTJoinRequest {
		return nil, errors.New("protocol: not a join request")
	}
	req := &JoinRequest{}
	reverseCopy(req.JoinEUI[:], raw[1:9])
	reverseCopy(req.DevEUI[:], raw[9:17])
	copy(req.DevNonce[:], raw[17:19])
	return req, nil
}

// VerifyJoinRequestMIC reports whether raw carries a valid Join-Request MIC.
func VerifyJoinRequestMIC(appKey lwcrypto.AES128Key, raw []byte) bool {
	if len(raw) != 23 {
		return false
	}
	return micOK(lwcrypto.JoinMessageMIC(appKey, raw[:19]), raw)
}

// MarshalJoinAccept serializes, ECB-encrypts and MICs a Join-Accept.
func MarshalJoinAccept(appKey lwcrypto.AES128Key, acc JoinAccept) ([]byte, error) {
	// MHDR | AppNonce | NetID | DevAddr | DLSettings | RXDelay | CFList(absent)
	plain := make([]byte, 13)
	plain[0] = mhdr(MTJoinAccept)
	copy(plain[1:4], acc.AppNonce[:])
	copy(plain[4:7], acc.NetID[:])
	copy(plain[7:11], acc.DevAddr[:])
	plain[11] = acc.DLSettings
	plain[12] = acc.RXDelay

	mic := lwcrypto.JoinMessageMIC(appKey, plain)
	// The MHDR stays in cleartext; everything after it (body + MIC) is
	// AES-ECB encrypted with the LoRaWAN byte-reversed ECB transform.
	encrypted := lwcrypto.EncryptJoinAcceptPayload(appKey, append(plain[1:], mic[:]...))
	return append([]byte{plain[0]}, encrypted...), nil
}

// ParseJoinAccept verifies the MIC, decrypts and parses a Join-Accept.
func ParseJoinAccept(appKey lwcrypto.AES128Key, raw []byte) (*JoinAccept, error) {
	if len(raw) != 17 && len(raw) != 33 {
		return nil, errBadJoinAccept
	}
	// Encryption covers: body(13 or 29) + MIC(4), i.e. the last 16 or
	// 32 bytes; MHDR is sent in cleartext.
	encrypted := raw[1:]
	decrypted, err := lwcrypto.DecryptJoinAcceptPayload(appKey, encrypted)
	if err != nil {
		return nil, err
	}
	// MIC is computed over MHDR || plaintext (excluding MIC bytes).
	micInput := make([]byte, 0, 1+len(decrypted)-4)
	micInput = append(micInput, raw[0])
	micInput = append(micInput, decrypted[:len(decrypted)-4]...)
	if !micOK(lwcrypto.JoinMessageMIC(appKey, micInput), decrypted) {
		return nil, ErrJoinAcceptMIC
	}
	acc := &JoinAccept{}
	copy(acc.AppNonce[:], decrypted[0:3])
	copy(acc.NetID[:], decrypted[3:6])
	copy(acc.DevAddr[:], decrypted[6:10])
	acc.DLSettings = decrypted[10]
	acc.RXDelay = decrypted[11]
	return acc, nil
}

// MarshalDataFrame serializes a data frame, encrypting FRMPayload and
// appending the MIC. fcnt32 is the full 32-bit counter (only low 16 bits
// go on the wire).
func MarshalDataFrame(keys lwcrypto.SessionKeys, f DataFrame, fcnt32 uint32) ([]byte, error) {
	f.FCnt = uint16(fcnt32)

	fopts := make([]byte, 0)
	for _, cmd := range f.FOpts {
		fopts = append(fopts, cmd.CID)
		fopts = append(fopts, cmd.Payload...)
	}
	if len(fopts) > 15 {
		return nil, errors.New("protocol: FOpts exceeds 15 bytes")
	}

	// FRMPayload encryption (AppSKey for FPort != 0, NwkSKey for FPort 0).
	var payload []byte
	if f.FPort >= 0 {
		key := keys.AppSKey
		if f.FPort == 0 {
			key = keys.NwkSKey
		}
		payload = lwcrypto.EncryptFramePayload(key, f.DevAddr, isDownlink(f.MType), fcnt32, f.FRMPayload)
	}

	var fctrl byte
	if f.FCtrl.ADR {
		fctrl |= 0x80
	}
	if f.FCtrl.ADRACKReq {
		fctrl |= 0x40
	}
	if f.FCtrl.ACK {
		fctrl |= 0x20
	}
	if f.FCtrl.FPending {
		fctrl |= 0x10
	}
	fctrl |= byte(len(fopts)) & 0x0f

	mac := make([]byte, 0, 13+len(fopts)+1+len(payload)+4)
	mac = append(mac, mhdr(f.MType))
	// DevAddr is little-endian on the wire.
	devAddrLE := append([]byte(nil), f.DevAddr[:]...)
	for i, j := 0, len(devAddrLE)-1; i < j; i, j = i+1, j-1 {
		devAddrLE[i], devAddrLE[j] = devAddrLE[j], devAddrLE[i]
	}
	mac = append(mac, devAddrLE...)
	mac = append(mac, fctrl)
	mac = append(mac, byte(fcnt32), byte(fcnt32>>8))
	mac = append(mac, fopts...)
	if f.FPort >= 0 {
		mac = append(mac, byte(f.FPort))
		mac = append(mac, payload...)
	}

	mic := lwcrypto.ComputeMIC(keys.NwkSKey, f.DevAddr, isDownlink(f.MType), fcnt32, mac)
	return append(mac, mic[:]...), nil
}

// ParseDataFrame parses a data frame, verifies its MIC and decrypts
// FRMPayload. downlink selects the direction used for MIC/encryption and
// fcnt32 is the full 32-bit counter recovered by the MAC layer from the
// 16-bit wire FCnt and its counter window (the high bits are needed to
// compute the correct MIC/keystream).
func ParseDataFrame(keys lwcrypto.SessionKeys, downlink bool, fcnt32 uint32, raw []byte) (*DecodedFrame, error) {
	if len(raw) < 7+4 {
		return nil, errShortFrame
	}
	mtype := parseMHDR(raw[0])
	if mtype != MTUnconfirmedDataUp && mtype != MTUnconfirmedDataDN &&
		mtype != MTConfirmedDataUp && mtype != MTConfirmedDataDN {
		return nil, errors.New("protocol: not a MAC data frame")
	}
	if downlink != isDownlink(mtype) {
		return nil, errors.New("protocol: frame direction disagrees with MType")
	}

	var devAddr DevAddr
	copy(devAddr[:], raw[1:5])
	for i, j := 0, 3; i < j; i, j = i+1, j-1 {
		devAddr[i], devAddr[j] = devAddr[j], devAddr[i]
	}

	fctrl := raw[5]
	fcnt16 := binary.LittleEndian.Uint16(raw[6:8])
	if uint16(fcnt32) != fcnt16 {
		return nil, errors.New("protocol: recovered FCnt high bits disagree with wire FCnt")
	}

	body := raw[8 : len(raw)-4]
	foptsLen := int(fctrl & 0x0f)
	if foptsLen > len(body) {
		return nil, errors.New("protocol: FCtrl FOptsLen exceeds frame")
	}
	optsRaw := body[:foptsLen]
	rest := body[foptsLen:]

	fPort := -1
	var frmPayload []byte
	if len(rest) > 0 {
		fPort = int(rest[0])
		key := keys.AppSKey
		if fPort == 0 {
			key = keys.NwkSKey
		}
		frmPayload = lwcrypto.EncryptFramePayload(key, devAddr, downlink, fcnt32, rest[1:])
	} else if fPort == 0 {
		return nil, errors.New("protocol: FPort present but empty")
	}

	// Parse FOpts MAC commands (CID + fixed payload lengths).
	cmds, err := parseFOpts(downlink, optsRaw)
	if err != nil {
		return nil, err
	}

	micValid := micOK(lwcrypto.ComputeMIC(keys.NwkSKey, devAddr, downlink, fcnt32, raw[:len(raw)-4]), raw)

	return &DecodedFrame{
		DataFrame: DataFrame{
			MType:      mtype,
			DevAddr:    devAddr,
			FCtrl:      parseFCtrl(fctrl),
			FCnt:       fcnt16,
			FOpts:      cmds,
			FPort:      fPort,
			FRMPayload: frmPayload,
		},
		FCnt32:   fcnt32,
		MICValid: micValid,
	}, nil
}

func isDownlink(t MType) bool {
	return t == MTUnconfirmedDataDN || t == MTConfirmedDataDN
}

func parseFCtrl(b byte) FCtrl {
	return FCtrl{
		ADR:       b&0x80 != 0,
		ADRACKReq: b&0x40 != 0,
		ACK:       b&0x20 != 0,
		FPending:  b&0x10 != 0,
		FOptsLen:  b & 0x0f,
	}
}

// parseFOpts parses the MAC-command bytes carried in FOpts. downlink
// distinguishes Req from Ans commands because the two share a CID. Only
// commands known to this stack are accepted; unknown CIDs abort parsing so
// malformed input can never desynchronize the parser.
func parseFOpts(downlink bool, b []byte) ([]MACCommand, error) {
	var cmds []MACCommand
	for len(b) > 0 {
		cid := b[0]
		cmd := MACCommand{CID: cid}
		need := 0
		switch cid {
		case 0x03:
			if downlink {
				need = 4 // LinkADRReq
			} else {
				need = 1 // LinkADRAns
			}
		case 0x06:
			if downlink {
				need = 0 // DevStatusReq
			} else {
				need = 2 // DevStatusAns
			}
		default:
			return nil, errors.New("protocol: unknown MAC command in FOpts")
		}
		if len(b)-1 < need {
			return nil, errors.New("protocol: truncated MAC command in FOpts")
		}
		cmd.Payload = append([]byte(nil), b[1:1+need]...)
		cmds = append(cmds, cmd)
		b = b[1+need:]
	}
	return cmds, nil
}

